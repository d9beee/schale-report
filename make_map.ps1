# make_map.ps1 - read-only: list where each block of index.html starts, with line numbers -> CODEMAP_lines.md
# Run from the repo folder after every change:  powershell -ExecutionPolicy Bypass -File .\make_map.ps1
# Picks up: <style>/<script> boundaries, screens (class="screen"), block titles (comments with =====),
# short CSS titles (/* UPPERCASE */) and the main data / function declarations. index.html is never changed.
# This file is ASCII only (Windows PowerShell 5.1 reads scripts as ANSI).
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$page = Join-Path $root 'index.html'
$out  = Join-Path $root 'CODEMAP_lines.md'
if (-not (Test-Path $page)) { Write-Host 'STOP: index.html not found. Put this script in the repo root.'; exit 1 }
$lines = [IO.File]::ReadAllLines($page, [Text.Encoding]::UTF8)

# what counts as a landmark (first match wins)
$rules = @(
  @{ k='TAG';    re='^\s*</?(style|script)\b' },
  @{ k='SCREEN'; re='<div class="screen"' },
  @{ k='BLOCK';  re='(/\*|//)\s*=====' },
  @{ k='CSS';    re='^/\* [A-Z0-9][A-Z0-9 &/+:-]{3,} \*/' },
  # data tables: declared at the start of a line (HELP / MAP sit one level inside a function); local helpers like "const a=" are skipped
  @{ k='DATA';   re='^const (SSP|SS|S|A|BC|UEX|RST|STAT|BIO|TYPE|OWN|BOSSES3|BOSS_KEYS|AR|VD|JTR|JTYPE|JRW|LBG|CAST|L2D|SCR|GM|BFACE)\b|^\s+const (HELP|MAP)\b' },
  @{ k='FUNC';   re='^\s*function (gridCards|cards|chips|openStu|stuInfo|uePick|growBody|renderBan|curBan|renderTasks|taskList|renderCalc|planFor|route|zoomScr|fillShell|fit)\b' }
)
$md = New-Object System.Collections.Generic.List[string]
$md.Add("# CODEMAP_lines - auto, $(Get-Date -Format 'yyyy-MM-dd HH:mm') - index.html = $($lines.Count) lines")
$md.Add('')
$md.Add('Generated by make_map.ps1. Do not edit by hand: run the script again after changing index.html.')
$md.Add('')
$md.Add('| Line | Kind | Text |')
$md.Add('|---:|---|---|')
for ($i = 0; $i -lt $lines.Count; $i++) {
  $t = $lines[$i]
  foreach ($r in $rules) {
    if ($t -match $r.re) {
      $s = ($t.Trim() -replace '\|', '/' )
      if ($s.Length -gt 110) { $s = $s.Substring(0, 110) + '...' }
      $md.Add("| $($i + 1) | $($r.k) | ``$s`` |")
      break
    }
  }
}
[IO.File]::WriteAllLines($out, $md, (New-Object Text.UTF8Encoding $false))
Write-Host "Done: $($md.Count - 6) landmarks -> CODEMAP_lines.md"
